import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, readFileSync, writeFileSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {SessionManager} from '../runtime/releases/coding-1.5.2/node_modules/@earendil-works/pi-coding-agent/dist/index.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const json = path => JSON.parse(readFileSync(join(root, path), 'utf8'));

test('the bundled manifest and installed Pi dependency family match the exact pin', () => {
  const pinned = json('runtime/package.json').dependencies['@earendil-works/pi-coding-agent'];
  const release = 'runtime/releases/coding-' + pinned;
  assert.equal(json(release + '/manifest.json').version, pinned);
  for (const name of ['pi-coding-agent', 'pi-agent-core', 'pi-ai', 'pi-tui', 'pi-schema', 'pi-codemode', 'pi-mcp', 'pi-telemetry']) {
    assert.equal(json(`${release}/node_modules/@earendil-works/${name}/package.json`).version, pinned, name);
  }
});

test('a real Pi 1.3.0 session retains tools, compaction, model and thinking when continued', () => {
  // Generated by SessionManager from the actual 1.3.0 npm package. All messages
  // are synthetic; this fixture never contains user data or credentials.
  const fixture = readFileSync(join(root, 'tests/fixtures/pi-1.3.0-session.jsonl'), 'utf8');
  const oldRows = fixture.trim().split('\n').map(JSON.parse);
  const temp = mkdtempSync(join(tmpdir(), 'umeko-pi-upgrade-'));
  const file = join(temp, 'legacy.jsonl');
  try {
    writeFileSync(file, fixture);
    const manager = SessionManager.open(file);
    assert.equal(manager.getSessionName(), 'Pi 1.3.0 upgrade fixture');
    assert.equal(manager.getEntries().length, 12);
    const context = manager.buildSessionContext();
    assert.equal(context.thinkingLevel, 'medium');
    assert.deepEqual(context.model, {provider: 'umeko', modelId: 'compat-fixture'});
    assert.equal(context.messages[0].role, 'compactionSummary');
    assert.equal(context.messages[0].summary, 'Summary generated with Pi 1.3.0.');
    assert.equal(context.messages[0].tokensBefore, 12345);
    assert.equal(context.messages.length, 5);
    assert.match(JSON.stringify(context.messages), /Kept legacy answer/);
    assert.match(JSON.stringify(context.messages), /Legacy continuation/);
    assert.doesNotMatch(JSON.stringify(context.messages), /Before compaction/);
    const result = manager.getEntries().find(e => e.type === 'message' && e.message.role === 'toolResult');
    assert.equal(result.message.toolCallId, 'legacy-write');
    assert.equal(result.message.isError, false);
    const parentId = manager.getLeafId();
    const id = manager.appendMessage({role: 'user', content: [{type: 'text', text: 'Continued with the upgraded Pi.'}], timestamp: 1794000000001});
    const reopened = SessionManager.open(file);
    assert.equal(reopened.getEntry(id).parentId, parentId);
    assert.equal(reopened.getLeafId(), id);
    assert.equal(reopened.buildSessionContext().messages.length, 6);
    const rows = readFileSync(file, 'utf8').trim().split('\n').map(JSON.parse);
    assert.deepEqual(rows.slice(0, oldRows.length), oldRows);
    assert.equal(readFileSync(join(root, 'tests/fixtures/pi-1.3.0-session.jsonl'), 'utf8'), fixture);
  } finally {
    rmSync(temp, {recursive: true, force: true});
  }
});
