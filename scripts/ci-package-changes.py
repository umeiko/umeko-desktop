"""Select Windows CI packages and the native packages needed for stable releases."""
from fnmatch import fnmatchcase
import os
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.project_info import VERSION
from scripts.release_platforms import ALL_PLATFORMS, NATIVE_JOBS, select_platforms

RUNNERS = {
    'windows-x64': 'windows-2022',
    'linux-x64': 'ubuntu-22.04',
    'macos-arm64': 'macos-15',
    'macos-x64': 'macos-15-intel',
}

PACKAGE_RESOURCES = (
    'app/icons/',
    'runtime/umeko-docs/',
    # Generated by setup, but fail open if a PR explicitly changes them.
    'runtime/node/',
    'runtime/releases/',
)
PACKAGE_FILES = {
    'app/theme-prompt.txt',
    'app/character-defaults.json',
    'app/provider-presets.json',
    'runtime/umeko-operations.json',
    'runtime/webview-component.json',
}


def needs_packages(paths):
    return any(is_package_input(path) for path in paths)


def package_matrix(event, all_platforms, node_changed=False, *, version=VERSION):
    mode = 'all' if event == 'workflow_dispatch' and all_platforms == 'true' else 'windows'
    platforms = ALL_PLATFORMS if node_changed else select_platforms(mode, version)
    return {'include': [
        dict(name=NATIVE_JOBS[platform], runner=runner, platform=platform)
        for platform, runner in RUNNERS.items() if platform in platforms
    ]}


def is_package_input(path):
    if path.startswith(('tests/', 'docs/', 'docs-site/')):
        return False
    if (path in PACKAGE_FILES or path.startswith(PACKAGE_RESOURCES)
            or fnmatchcase(path, 'runtime/package*.json')
            or Path(path).match('requirements*.txt')
            or path.endswith('.spec')):
        return True
    # Ordinary source changes get shared + Windows-native PR checks. The full
    # main package job catches their packaging regressions before publication.
    if path.startswith(('app/', 'runtime/')):
        # QML module manifests, SVGs and newly added data files are packaging
        # inputs too. Only known source suffixes take the lighter PR path.
        return Path(path).suffix not in {'.py', '.pyi', '.qml', '.js', '.mjs', '.cjs'}
    if path in ('scripts/capture-documentation.py', '.github/workflows/docs.yml'):
        return False
    # Unclassified paths fail open: build/setup scripts, dependency pins,
    # packaging workflows/configuration and explicitly copied resources.
    return True


if __name__ == '__main__':
    event = os.environ.get('GITHUB_EVENT_NAME', 'pull_request')
    packages = True
    node_changed = False
    if event == 'pull_request':
        result = subprocess.run(
            ['git', 'diff', '--name-only', '-z', os.environ['PR_BASE'], 'HEAD'],
            check=True, capture_output=True,
            creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
        paths = result.stdout.decode('utf-8', errors='surrogateescape').split('\0')
        packages = needs_packages([p for p in paths if p])
        node_changed = 'scripts/node-distributions.json' in paths
    matrix = package_matrix(event, os.environ.get('CI_ALL_PLATFORMS', ''), node_changed)
    node_version = json.loads(Path('scripts/node-distributions.json').read_text(encoding='utf-8'))['version']
    with Path(os.environ['GITHUB_OUTPUT']).open('a', encoding='utf-8') as output:
        output.write(f'packages={str(packages).lower()}\n')
        output.write('matrix=' + json.dumps(matrix) + '\n')
        output.write('node_version=' + node_version + '\n')
    print(f'Native packages required: {packages}')
